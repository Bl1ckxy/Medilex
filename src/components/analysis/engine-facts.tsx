import { AlertTriangle, CalendarClock, Coins, Cog, Gavel } from 'lucide-react';
import { Panel } from '@/components/shared/ui';
import { cn, formatCurrency, formatDate } from '@/lib/utils';
import { normalizeCitation } from '@/lib/ai/citation-checker';
import {
    GATE_BADGE_STYLES,
    GATE_DOT_STYLES,
    GATE_LABELS,
    gateStatusForCitation,
    type CitationCheckLike,
    type GateStatus,
} from '@/lib/legal/citation-status';

export type EngineFacts = {
    limitation: {
        deadline: string;
        daysRemaining: number;
        isExpired: boolean;
        isWarningZone: boolean;
        isCriticalZone: boolean;
        condonationPossible: boolean;
    };
    forum: {
        forum: string;
        displayName: string;
        jurisdiction: string;
        filingFeeINR: number;
    };
    compensation: {
        total: number;
        scope: string;
    };
};

export type DeviationInfo = {
    aiMidpoint: number;
    engineTotal: number;
    deltaPercent: number;
    exceedsThreshold: boolean;
    reason: string | null;
} | null;

export type AuthorityLite = {
    citation: string;
    title: string;
    source_type: string;
    court: string | null;
    year: number | null;
    similarity: number;
};

export type GroundingLite = {
    chunks: AuthorityLite[];
    skippedReason: string | null;
};

function EngineChip() {
    return (
        <span className="inline-flex items-center gap-1 text-[10px] font-medium text-slate-400" title="Deterministic output — computed from case fields, not generated by the model">
            <Cog className="h-3 w-3" aria-hidden="true" />
            Computed by engine
        </span>
    );
}

function GateBadge({ status, note }: { status: GateStatus; note: string }) {
    return (
        <span
            title={note}
            className={cn('inline-flex items-center gap-1.5 rounded-full border px-2 py-0.5 text-[10px] font-semibold', GATE_BADGE_STYLES[status])}
        >
            <span className={cn('h-1.5 w-1.5 rounded-full', GATE_DOT_STYLES[status])} aria-hidden="true" />
            {GATE_LABELS[status]}
        </span>
    );
}

export function EngineFactsStrip({ engine }: { engine: EngineFacts }) {
    const limitationTone = engine.limitation.isExpired || engine.limitation.isCriticalZone
        ? 'border-crimson-100'
        : engine.limitation.isWarningZone
            ? 'border-gold-200'
            : 'border-slate-200';
    const limitationValueTone = engine.limitation.isExpired || engine.limitation.isCriticalZone
        ? 'text-crimson'
        : engine.limitation.isWarningZone
            ? 'text-gold-600'
            : 'text-navy';

    let limitationNote: string;
    if (engine.limitation.isExpired) {
        limitationNote = `Expired ${Math.abs(engine.limitation.daysRemaining)} days ago${engine.limitation.condonationPossible ? ' — condonation may be available' : ''}`;
    } else if (engine.limitation.isCriticalZone) {
        limitationNote = `${engine.limitation.daysRemaining} days left — critical`;
    } else if (engine.limitation.isWarningZone) {
        limitationNote = `${engine.limitation.daysRemaining} days remaining — warning zone`;
    } else {
        limitationNote = `${engine.limitation.daysRemaining} days remaining`;
    }

    return (
        <section aria-label="Engine-computed facts">
            <div className="flex items-center justify-between gap-3">
                <h3 className="text-xs font-semibold text-slate-500">Engine-computed facts</h3>
                <EngineChip />
            </div>
            <div className="mt-2 grid gap-4 md:grid-cols-3">
                <div className={cn('rounded-lg border bg-white p-4 shadow-sm', limitationTone)}>
                    <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                        <CalendarClock className={cn('h-4 w-4', limitationValueTone)} aria-hidden="true" />
                        Limitation deadline
                    </div>
                    <p className={cn('mt-2 text-lg font-semibold tabular-nums', limitationValueTone)}>{formatDate(engine.limitation.deadline)}</p>
                    <p className="mt-1 text-xs leading-5 text-slate-500">{limitationNote}</p>
                </div>
                <div className="rounded-lg border border-slate-200 bg-white p-4 shadow-sm">
                    <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                        <Gavel className="h-4 w-4 text-navy" aria-hidden="true" />
                        Recommended forum
                    </div>
                    <p className="mt-2 text-sm font-semibold leading-5 text-navy">{engine.forum.displayName}</p>
                    <p className="mt-1 text-xs leading-5 text-slate-500">
                        {engine.forum.jurisdiction} · court fee {formatCurrency(engine.forum.filingFeeINR)}
                    </p>
                </div>
                <div className="rounded-lg border border-slate-200 bg-white p-4 shadow-sm">
                    <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                        <Coins className="h-4 w-4 text-navy" aria-hidden="true" />
                        Formulaic compensation
                    </div>
                    <p className="mt-2 text-lg font-semibold tabular-nums text-navy">{formatCurrency(engine.compensation.total)}</p>
                    <p className="mt-1 text-xs leading-5 text-slate-500">{engine.compensation.scope}</p>
                </div>
            </div>
        </section>
    );
}

export function DeviationBanner({ deviation }: { deviation: DeviationInfo }) {
    if (!deviation || !deviation.exceedsThreshold) return null;
    const direction = deviation.deltaPercent >= 0 ? 'above' : 'below';
    return (
        <div role="status" className="flex items-start gap-3 rounded-md border border-gold-200 bg-gold-50 px-4 py-3">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-gold-600" aria-hidden="true" />
            <div className="text-sm">
                <p className="font-semibold text-navy">
                    AI compensation estimate is {Math.abs(deviation.deltaPercent)}% {direction} the formulaic baseline
                </p>
                <p className="mt-0.5 text-xs leading-5 text-slate-600">
                    Analysis midpoint {formatCurrency(deviation.aiMidpoint)} · engine baseline {formatCurrency(deviation.engineTotal)} — the baseline
                    covers the severity-table heads only; economic heads need income and treatment inputs.
                    {deviation.reason ? ` Analysis note: ${deviation.reason}` : ''}
                </p>
            </div>
        </div>
    );
}

const TYPE_CHIP_STYLES: Record<string, string> = {
    statute: 'bg-navy-50 text-navy',
    case: 'bg-gold-50 text-gold-600',
    doctrine: 'bg-violet-50 text-violet-700',
    guideline: 'bg-emerald-50 text-emerald-700',
    practice: 'bg-sky-50 text-sky-700',
};

export function AuthoritiesCard({
    grounding,
    cited,
    check,
}: {
    grounding: GroundingLite;
    cited: string[];
    check: CitationCheckLike;
}) {
    const citedNorms = new Set(cited.map((item) => normalizeCitation(item)));
    return (
        <Panel
            title="Authorities"
            description="Retrieved from the curated corpus — the only sources this analysis is permitted to cite."
            action={<span className="text-[11px] tabular-nums text-slate-400">{grounding.chunks.length} retrieved</span>}
        >
            {grounding.chunks.length === 0 ? (
                <div className="px-5 py-4 text-xs leading-5 text-slate-500">
                    No authorities were retrieved for this matter{grounding.skippedReason ? ` (${grounding.skippedReason})` : ''} — the analysis ran without
                    corpus grounding and must be reviewed line by line.
                </div>
            ) : (
                <div className="overflow-x-auto">
                    <table className="w-full min-w-[720px] text-left text-xs">
                        <thead className="border-b border-slate-100 bg-slate-50/70 text-[11px] text-slate-500">
                            <tr>
                                <th className="px-4 py-2 font-semibold">Ref</th>
                                <th className="px-4 py-2 font-semibold">Citation</th>
                                <th className="px-4 py-2 font-semibold">Type</th>
                                <th className="px-4 py-2 font-semibold">Court</th>
                                <th className="px-4 py-2 font-semibold">Year</th>
                                <th className="px-4 py-2 font-semibold">Similarity</th>
                                <th className="px-4 py-2 text-right font-semibold">Gate</th>
                            </tr>
                        </thead>
                        <tbody className="divide-y divide-slate-100">
                            {grounding.chunks.map((chunk, index) => {
                                const inAnswer = citedNorms.has(normalizeCitation(chunk.citation));
                                let { status, note } = gateStatusForCitation(chunk.citation, check);
                                if (status === 'uncited' && inAnswer) {
                                    status = 'partial';
                                    note = 'Cited by the analysis; not separately gate-checked.';
                                }
                                return (
                                    <tr key={`${chunk.citation}-${index}`} className="transition-colors hover:bg-slate-50">
                                        <td className="px-4 py-2.5">
                                            <span className="rounded border border-navy-100 bg-navy-50 px-1.5 py-px text-[10px] font-semibold tabular-nums text-navy">
                                                A{index + 1}
                                            </span>
                                        </td>
                                        <td className="px-4 py-2.5">
                                            <p className="font-serif text-[13px] font-semibold leading-5 text-navy">{chunk.citation}</p>
                                            <p className="mt-0.5 text-[11px] leading-4 text-slate-500">{chunk.title}</p>
                                        </td>
                                        <td className="px-4 py-2.5">
                                            <span className={cn('rounded-full px-2 py-0.5 text-[10px] font-semibold', TYPE_CHIP_STYLES[chunk.source_type] ?? 'bg-slate-100 text-slate-600')}>
                                                {chunk.source_type}
                                            </span>
                                        </td>
                                        <td className="px-4 py-2.5 text-slate-600">{chunk.court ?? '—'}</td>
                                        <td className="px-4 py-2.5 tabular-nums text-slate-600">{chunk.year ?? 'n.d.'}</td>
                                        <td className="px-4 py-2.5 font-medium tabular-nums text-slate-600" title="Cosine similarity to the grounding query">
                                            {Math.max(0, Math.round(chunk.similarity * 100))}%
                                        </td>
                                        <td className="px-4 py-2.5 text-right">
                                            <GateBadge status={status} note={note} />
                                        </td>
                                    </tr>
                                );
                            })}
                        </tbody>
                    </table>
                </div>
            )}
        </Panel>
    );
}
